def test_lifecycle_failures_and_duplicate_ids():
    g = graph()
    for operation in (lambda: observe(g, 0, 0), lambda: g.depart(0), g.end_segment):
        with pytest.raises(ValueError, match="begin_segment"): operation()
    g.begin_segment("a", coordinate_kind="order_index")
    with pytest.raises(ValueError, match="end the active"): g.begin_segment("b", coordinate_kind="seconds")
    g.end_segment()
    with pytest.raises(ValueError, match="never reused"): g.begin_segment("a", coordinate_kind="order_index")


def test_all_exported_pose_and_decision_coordinates_explicit_no_fake_seconds():
    g = graph(); abc(g); g.end_segment()
    def inspect(value):
        if isinstance(value, dict):
            assert "timestamp_s" not in value and "duration_s" not in value
            for nested in value.values(): inspect(nested)
        elif isinstance(value, (tuple, list)):
            for nested in value: inspect(nested)
    state = g.snapshot(); inspect(state)
    assert state["legacy_clock_adapter"] == "PRIVATE_CALL_ORDINAL_NOT_SECONDS"
    assert state["time_metrics_available"] is False
    assert state["nodes"][0]["pose"]["coordinate"] == {"segment_id": "first", "kind": "order_index", "value": 0}
    s = graph(); s.begin_segment("seconds", coordinate_kind="seconds"); observe(s, 12.5, 0, kind="seconds")
    assert s.snapshot()["nodes"][0]["pose"]["coordinate"]["value"] == 12.5


