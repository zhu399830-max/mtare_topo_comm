def test_caller_mutation_of_pose_cannot_rewrite_stored_edge_trace():
    g = graph(); g.begin_segment("a", coordinate_kind="order_index")
    xyz = [0., 0., 0.]
    g.update(SegmentObservation("junction", .99, .01, (PORT,)), SegmentPose(xyz, [.01] * 3),
             coordinate=SegmentCoordinate("order_index", 0))
    g.depart(0); xyz[0] = 1000
    observe(g, 1, 5, "corridor"); observe(g, 2, 10)
    assert g.snapshot()["edges"][0]["length_m"] == 10
